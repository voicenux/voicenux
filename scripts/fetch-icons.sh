#!/bin/sh
# Downloads the icons of voices, sounds and effects from game-icons.net (CC BY 3.0, see
# data/icons/LICENSE). The files are committed, so this only runs when the list changes.
# The black background square is dropped and the fill removed, so GTK can color them.
set -eu
base="https://raw.githubusercontent.com/game-icons/icons/master"
out="$(dirname "$0")/../data/icons"
mkdir -p "$out"

while IFS='|' read -r name path; do
	[ -z "$name" ] && continue
	[ -f "$out/$name.svg" ] && continue
	echo "$name"
	curl -fsSL "$base/$path" | sed -e 's|<path d="M0 0h512v512H0z"/>||' -e 's| fill="#fff"||g' > "$out/$name.svg"
done <<'LIST'
